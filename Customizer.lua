                effects += 1
            end
        elseif object:IsA("MeshPart")
            or object:IsA("SpecialMesh")
            or object:IsA("Decal")
            or object:IsA("Texture") then
            changeGunObject(object)
            textures += 1
        elseif object:IsA("Beam") or object:IsA("Trail") then
            applyEffectColor(object)
            effects += 1
        end
    end

    shared.Notify(
        CURRENT_STYLE .. " applied • "
            .. textures .. " textures • "
            .. effects .. " effects",
        2
    )
end

local function restoreGun(tool)
    for object, properties in pairs(originalGunProperties) do
        if object and object.Parent then
            for property, originalValue in pairs(properties) do
                pcall(function()
                    object[property] = originalValue
                end)
            end
        end
    end

    originalGunProperties = {}

    if equippedGun == tool then
        equippedGun = nil
    end
end

local function restoreDisplay()
    for object, properties in pairs(originalDisplayTextures) do
        if object and object.Parent then
            for property, originalValue in pairs(properties) do
                pcall(function()
                    object[property] = originalValue
                end)
            end
        end
    end

    originalDisplayTextures = {}
    selectedGunDisplay = nil
end

local function resetToNormal()
    restoreDisplay()

    if equippedGun then
        restoreGun(equippedGun)
    end

    local character = player.Character
    if character then
        for _, object in ipairs(character:GetChildren()) do
            if object:IsA("Tool") and object.Name == GUN_TOOL_NAME then
                restoreGun(object)
            end
        end
    end

    local backpack = player:FindFirstChild("Backpack")
    if backpack then
        for _, object in ipairs(backpack:GetChildren()) do
            if object:IsA("Tool") and object.Name == GUN_TOOL_NAME then
                restoreGun(object)
            end
        end
    end

    CURRENT_STYLE = "Normal"
    TEXTURE_ID = nil
    BEAM_COLOR = nil

    shared.Notify("NORMAL • Original color restored.", 2)
end

local function selectStyle(styleName)
    local selectedStyle = nil
    for _, style in ipairs(Styles) do
        if style.Name == styleName then
            selectedStyle = style
            break
        end
    end

    if not selectedStyle then return end

    local gunToReapply = equippedGun

    restoreDisplay()
    if equippedGun then
        restoreGun(equippedGun)
    end

    CURRENT_STYLE = selectedStyle.Name
    TEXTURE_ID = selectedStyle.Texture
    BEAM_COLOR = selectedStyle.Beam

    if CURRENT_STYLE == "Normal" then
        shared.Notify("NORMAL • Original color restored.", 2)
        return
    end

    local target, distance, errorMessage = findNearestGunDisplay()

    if not target then
        shared.Notify(errorMessage, 3)
        return
    end

    selectedGunDisplay = target
    local changed = changeDisplayTextures(target)

    if changed == 0 then
        shared.Notify("No editable GunDisplay objects found.", 3)
    else
        shared.Notify(
            CURRENT_STYLE .. " selected • "
                .. math.floor(distance) .. " studs",
            2
        )
    end

    if CURRENT_STYLE == "GhostScope"
        and gunToReapply
        and gunToReapply.Parent then
        applyStyleToGun(gunToReapply)
    end
end

local function setupTool(tool)
    if not tool:IsA("Tool") then return end
    if tool.Name ~= GUN_TOOL_NAME then return end
    if connectedTools[tool] then return end

    connectedTools[tool] = true
    toolEffectConnections[tool] = {}

    local function prepareEffect(object)
        if not (object:IsA("Beam") or object:IsA("Trail")) then return end

        saveGunOriginal(object, "Color")
        saveGunOriginal(object, "Transparency")

        local connection = object:GetPropertyChangedSignal("Color"):Connect(function()
            if equippedGun ~= tool then return end
            if CURRENT_STYLE == "Normal" then return end
            if not object.Parent then return end

            if CURRENT_STYLE == "GhostScope" then
                changeGunObject(object)
            else
                applyEffectColor(object)
            end
        end)

        table.insert(toolEffectConnections[tool], connection)

        if equippedGun == tool and CURRENT_STYLE ~= "Normal" then
            changeGunObject(object)
        end
    end

    for _, object in ipairs(tool:GetDescendants()) do
        prepareEffect(object)
    end

    gunDescendantConnections[tool] = tool.DescendantAdded:Connect(function(object)
        if object:IsA("Beam") or object:IsA("Trail") then
            prepareEffect(object)
        end
        if equippedGun == tool and CURRENT_STYLE ~= "Normal" then
            changeGunObject(object)
        end
    end)

    tool.Equipped:Connect(function()
        equippedGun = tool
        if CURRENT_STYLE ~= "Normal" then
            applyStyleToGun(tool)
        end
    end)

    tool.Unequipped:Connect(function()
        restoreGun(tool)
    end)

    tool.Destroying:Connect(function()
        connectedTools[tool] = nil

        if toolEffectConnections[tool] then
            for _, connection in ipairs(toolEffectConnections[tool]) do
                connection:Disconnect()
            end
            toolEffectConnections[tool] = nil
        end

        if gunDescendantConnections[tool] then
            gunDescendantConnections[tool]:Disconnect()
            gunDescendantConnections[tool] = nil
        end
    end)
end

local function setupCharacter(character)
    for _, object in ipairs(character:GetChildren()) do
        if object:IsA("Tool") then
            setupTool(object)
        end
    end

    character.ChildAdded:Connect(function(object)
        if object:IsA("Tool") then
            setupTool(object)
        end
    end)
end

local function setupBackpack()
    local backpack = player:WaitForChild("Backpack")
    for _, object in ipairs(backpack:GetChildren()) do
        if object:IsA("Tool") then
            setupTool(object)
        end
    end

    backpack.ChildAdded:Connect(function(object)
        if object:IsA("Tool") then
            setupTool(object)
        end
    end)
end

if player.Character then
    setupCharacter(player.Character)
end

