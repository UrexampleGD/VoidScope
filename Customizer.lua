local function safeCall(fn, ...)
    if type(fn) ~= "function" then return end
    pcall(fn, ...)
end

local function getObjectPosition(object)
    if object:IsA("BasePart") then
        return object.Position
    end

    if object:IsA("Model") then
        local part = object.PrimaryPart
            or object:FindFirstChildWhichIsA("BasePart", true)
        if part then
            return part.Position
        end
    end

    if object:IsA("Tool") then
        local handle = object:FindFirstChild("Handle", true)
        if handle and handle:IsA("BasePart") then
            return handle.Position
        end
    end

    return nil
end

local function findNearestGunDisplay()
    local character = player.Character
    local root = character
        and character:FindFirstChild("HumanoidRootPart")

    if not root then
        return nil, nil, "Character isn't loaded."
    end

    local nearest = nil
    local nearestDistance = math.huge

    for _, object in ipairs(workspace:GetDescendants()) do
        if object.Name == TARGET_NAME then
            local position = getObjectPosition(object)
            if position then
                local distance = (position - root.Position).Magnitude
                if distance < nearestDistance then
                    nearestDistance = distance
                    nearest = object
                end
            end
        end
    end

    if not nearest then
        return nil, nil, "No GunDisplay found."
    end

    return nearest, nearestDistance
end

local function saveDisplayOriginal(object, property)
    if not originalDisplayTextures[object] then
        originalDisplayTextures[object] = {}
    end
    if originalDisplayTextures[object][property] == nil then
        originalDisplayTextures[object][property] = object[property]
    end
end

local function saveGunOriginal(object, property)
    if not originalGunProperties[object] then
        originalGunProperties[object] = {}
    end
    if originalGunProperties[object][property] == nil then
        originalGunProperties[object][property] = object[property]
    end
end

local function changeDisplayTextures(root)
    if not root or not root.Parent then
        return 0
    end

    local changed = 0

    local function change(object, property, value)
        local success = pcall(function()
            saveDisplayOriginal(object, property)
            object[property] = value
        end)
        if success then
            changed += 1
        end
    end

    if CURRENT_STYLE == "GhostScope" then
        local function ghostObject(object)
            if object:IsA("BasePart") then
                change(object, "Color", WHITE)
                change(object, "Transparency", 0.5)
                if object:IsA("MeshPart") then
                    change(object, "TextureID", "")
                end
            elseif object:IsA("SpecialMesh") then
                change(object, "TextureId", "")
                local parent = object.Parent
                if parent and parent:IsA("BasePart") then
                    change(parent, "Color", WHITE)
                    change(parent, "Transparency", 0.5)
                end
            elseif object:IsA("Decal") or object:IsA("Texture") then
                change(object, "Transparency", 1)
            elseif object:IsA("Beam") or object:IsA("Trail") then
                change(object, "Color", ColorSequence.new(WHITE))
                change(object, "Transparency", NumberSequence.new(0.5))
            end
        end

        ghostObject(root)
        for _, object in ipairs(root:GetDescendants()) do
            ghostObject(object)
        end
        return changed
    end

    if not TEXTURE_ID then
        return 0
    end

    local function changeTexture(object)
        if object:IsA("MeshPart") then
            change(object, "TextureID", TEXTURE_ID)
        elseif object:IsA("SpecialMesh") then
            change(object, "TextureId", TEXTURE_ID)
        elseif object:IsA("Decal") or object:IsA("Texture") then
            change(object, "Texture", TEXTURE_ID)
        end
    end

    changeTexture(root)
    for _, object in ipairs(root:GetDescendants()) do
        changeTexture(object)
    end

    return changed
end

local function applyEffectColor(object)
    if not object then return end
    if not (object:IsA("Beam") or object:IsA("Trail")) then return end

    saveGunOriginal(object, "Color")

    if CURRENT_STYLE == "GhostScope" then
        saveGunOriginal(object, "Transparency")
        object.Color = ColorSequence.new(WHITE)
        object.Transparency = NumberSequence.new(0.5)
    elseif CURRENT_STYLE == "VoidScope" then
        object.Color = ColorSequence.new({
            ColorSequenceKeypoint.new(0, Color3.fromRGB(255, 255, 255)),
            ColorSequenceKeypoint.new(0.5, Color3.fromRGB(170, 170, 170)),
            ColorSequenceKeypoint.new(1, Color3.fromRGB(0, 0, 0)),
        })
    elseif BEAM_COLOR then
        object.Color = ColorSequence.new(BEAM_COLOR)
    end
end

local function changeGunObject(object)
    if not equippedGun then return end
    if equippedGun.Name ~= GUN_TOOL_NAME then return end

    if CURRENT_STYLE == "GhostScope" then
        if object:IsA("BasePart") then
            saveGunOriginal(object, "Color")
            saveGunOriginal(object, "Transparency")
            object.Color = WHITE
            object.Transparency = 0.5
            if object:IsA("MeshPart") then
                saveGunOriginal(object, "TextureID")
                object.TextureID = ""
            end
        elseif object:IsA("SpecialMesh") then
            saveGunOriginal(object, "TextureId")
            object.TextureId = ""
            local parent = object.Parent
            if parent and parent:IsA("BasePart") then
                saveGunOriginal(parent, "Color")
                saveGunOriginal(parent, "Transparency")
                parent.Color = WHITE
                parent.Transparency = 0.5
            end
        elseif object:IsA("Decal") or object:IsA("Texture") then
            saveGunOriginal(object, "Transparency")
            object.Transparency = 1
        elseif object:IsA("Beam") or object:IsA("Trail") then
            saveGunOriginal(object, "Color")
            saveGunOriginal(object, "Transparency")
            object.Color = ColorSequence.new(WHITE)
            object.Transparency = NumberSequence.new(0.5)
        end
        return
    end

    if not TEXTURE_ID then return end

    if object:IsA("MeshPart") then
        saveGunOriginal(object, "TextureID")
        object.TextureID = TEXTURE_ID
    elseif object:IsA("SpecialMesh") then
        saveGunOriginal(object, "TextureId")
        object.TextureId = TEXTURE_ID
    elseif object:IsA("Decal") or object:IsA("Texture") then
        saveGunOriginal(object, "Texture")
        object.Texture = TEXTURE_ID
    elseif object:IsA("Beam") or object:IsA("Trail") then
        applyEffectColor(object)
    end
end

